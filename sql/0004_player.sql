-- player entity: one player, keyed by GSIS ID (ETL spec §7.2.1, data dictionary A5; ADR-0005).
-- Single file, replaced whole; no foreign key points at it, since rosters reference players
-- missing from players.csv (§7.2.3). Team-code columns carry foreign keys to team (§7.2).
-- Apply by hand (ADR-0011). Column types and nullability follow §7.2.2.

CREATE TABLE IF NOT EXISTS player (
  gsis_id                      VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name                 VARCHAR(64)  NULL,
  common_first_name            VARCHAR(32)  NULL,
  first_name                   VARCHAR(32)  NULL,
  last_name                    VARCHAR(32)  NULL,
  short_name                   VARCHAR(32)  NULL,
  football_name                VARCHAR(32)  NULL,
  suffix                       VARCHAR(16)  NULL,
  esb_id                       VARCHAR(16) CHARACTER SET ascii NULL,
  nfl_id                       INT UNSIGNED NULL,
  pfr_id                       VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NULL,
  pff_id                       INT UNSIGNED NULL,
  otc_id                       INT UNSIGNED NULL,
  espn_id                      INT UNSIGNED NULL,
  smart_id                     VARCHAR(64) CHARACTER SET ascii NULL,
  birth_date                   DATE         NULL,
  position_group               VARCHAR(8)  CHARACTER SET ascii NULL,
  position                     VARCHAR(4)  CHARACTER SET ascii NULL,
  ngs_position_group           VARCHAR(8)   NULL,
  ngs_position                 VARCHAR(32)  NULL,
  height                       TINYINT UNSIGNED  NULL,
  weight                       SMALLINT UNSIGNED NULL,
  headshot                     VARCHAR(128) NULL,
  college_name                 VARCHAR(128) NULL,
  college_conference           VARCHAR(64)  NULL,
  jersey_number                TINYINT UNSIGNED  NULL,
  rookie_season                SMALLINT UNSIGNED NULL,
  last_season                  SMALLINT UNSIGNED NULL,
  latest_team                  VARCHAR(4) CHARACTER SET ascii NULL,
  status                       VARCHAR(4)   NULL,
  ngs_status                   VARCHAR(4)   NULL,
  ngs_status_short_description VARCHAR(32)  NULL,
  years_of_experience          TINYINT UNSIGNED NULL,
  pff_position                 VARCHAR(4)   NULL,
  pff_status                   VARCHAR(8)   NULL,
  draft_year                   SMALLINT UNSIGNED NULL,
  draft_round                  TINYINT UNSIGNED  NULL,
  draft_pick                   SMALLINT UNSIGNED NULL,
  draft_team                   VARCHAR(4) CHARACTER SET ascii NULL,
  PRIMARY KEY (gsis_id),
  CONSTRAINT fk_player_latest_team FOREIGN KEY (latest_team) REFERENCES team (team_abbr),
  CONSTRAINT fk_player_draft_team  FOREIGN KEY (draft_team)  REFERENCES team (team_abbr)
) ENGINE = InnoDB;
