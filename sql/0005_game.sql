-- game entity: one game, keyed by game_id (ETL spec §7.2.1, data dictionary A3; ADR-0005).
-- Single file (all seasons), replaced whole; no foreign key points at it (§7.2.3). The two
-- team columns carry foreign keys to team; the starting-QB IDs are player references with
-- none (§7.2). Apply by hand (ADR-0011). Types and nullability follow §7.2.2; timestamps UTC.

CREATE TABLE IF NOT EXISTS game (
  game_id          VARCHAR(32) CHARACTER SET ascii NOT NULL,
  season           SMALLINT UNSIGNED NULL,
  game_type        ENUM('CON','DIV','REG','SB','WC') NULL,
  week             TINYINT UNSIGNED NULL,
  gameday          DATE         NULL,
  weekday          VARCHAR(16)  NULL,
  gametime         TIME         NULL,
  away_team        VARCHAR(4) CHARACTER SET ascii NULL,
  away_score       TINYINT UNSIGNED NULL,
  home_team        VARCHAR(4) CHARACTER SET ascii NULL,
  home_score       TINYINT UNSIGNED NULL,
  location         ENUM('Home','Neutral') NULL,
  result           TINYINT      NULL,
  total            TINYINT UNSIGNED NULL,
  overtime         TINYINT UNSIGNED NULL,
  old_game_id      INT UNSIGNED NULL,
  gsis             INT UNSIGNED NULL,
  nfl_detail_id    VARCHAR(64) CHARACTER SET ascii NULL,
  pfr              VARCHAR(16) CHARACTER SET ascii NULL,
  pff              SMALLINT UNSIGNED NULL,
  espn             INT UNSIGNED NULL,
  ftn              SMALLINT UNSIGNED NULL,
  away_rest        TINYINT UNSIGNED NULL,
  home_rest        TINYINT UNSIGNED NULL,
  away_moneyline   SMALLINT     NULL,
  home_moneyline   SMALLINT     NULL,
  spread_line      DOUBLE       NULL,
  away_spread_odds SMALLINT     NULL,
  home_spread_odds SMALLINT     NULL,
  total_line       DOUBLE       NULL,
  under_odds       SMALLINT     NULL,
  over_odds        SMALLINT     NULL,
  div_game         TINYINT UNSIGNED NULL,
  roof             VARCHAR(16)  NULL,
  surface          VARCHAR(16)  NULL,
  temp             SMALLINT     NULL,
  wind             TINYINT UNSIGNED NULL,
  away_qb_id       VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NULL,
  home_qb_id       VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NULL,
  away_qb_name     VARCHAR(32)  NULL,
  home_qb_name     VARCHAR(32)  NULL,
  away_coach       VARCHAR(32)  NULL,
  home_coach       VARCHAR(32)  NULL,
  referee          VARCHAR(32)  NULL,
  stadium_id       VARCHAR(8) CHARACTER SET ascii NULL,
  stadium          VARCHAR(64)  NULL,
  PRIMARY KEY (game_id),
  CONSTRAINT fk_game_away_team FOREIGN KEY (away_team) REFERENCES team (team_abbr),
  CONSTRAINT fk_game_home_team FOREIGN KEY (home_team) REFERENCES team (team_abbr)
) ENGINE = InnoDB;
